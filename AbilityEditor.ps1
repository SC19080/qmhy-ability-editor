# ---------- 列表刷新 ----------
function Refresh-List {
    $lv.BeginUpdate()
    $lv.Items.Clear()
    $kw = $txtSearch.Text.Trim()
    foreach ($m in $MonList) {
        $pair = Get-EffPair $m
        $isDual = ($pair[1] -ne 0 -and $pair[1] -ne $pair[0])
        if ($chkDual.Checked -and -not $isDual) { continue }
        if ($chkSingle.Checked -and $isDual) { continue }
        if ($chkMod.Checked -and -not $script:Pending.ContainsKey($m.Slot)) { continue }
        if ($kw -and ($m.Name -notlike ('*' + $kw + '*'))) {
            $hasAb = $false
            foreach ($k in $pair) {
                if ((Get-AbName $k) -like ('*' + $kw + '*')) { $hasAb = $true; break }
            }
            if (-not $hasAb) { continue }
        }
        $dex = ''; if ($m.Sp -gt 0) { $dex = $m.Sp.ToString() }
        $it = New-Object System.Windows.Forms.ListViewItem($dex)
        [void]$it.SubItems.Add($m.Name)
        $mark = ''
        if ($script:Pending.ContainsKey($m.Slot)) { $mark = ' *' }
        [void]$it.SubItems.Add((Get-AbName $pair[0]) + $mark)
        if ($pair[1] -eq 0) { [void]$it.SubItems.Add('') }
        elseif ($pair[1] -eq $pair[0]) { [void]$it.SubItems.Add('（复写）' + $mark) }
        else { [void]$it.SubItems.Add((Get-AbName $pair[1]) + $mark) }
        $st6 = Get-EffStats $m
        [void]$it.SubItems.Add(($st6 -join ','))
        $st = ''
        if ($script:Pending.ContainsKey($m.Slot)) {
            $st = '已修改(暂存)'; $it.BackColor = [System.Drawing.Color]::LemonChiffon
        }
        [void]$it.SubItems.Add($st)
        $it.Tag = $m
        [void]$lv.Items.Add($it)
    }
    $lv.EndUpdate()
    $lblPending.Text = ('暂存修改: {0} 处' -f $script:Pending.Count)
}

