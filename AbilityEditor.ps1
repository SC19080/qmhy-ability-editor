# ---------- 载入 ROM ----------
function Load-Rom([string]$path) {
    if ([string]::IsNullOrWhiteSpace($path)) { return }
    if (-not [System.IO.File]::Exists($path)) {
        [void][System.Windows.Forms.MessageBox]::Show('文件不存在（注意：不能是文件夹）', '错误')
        return
    }
    try {
        $bytes = [System.IO.File]::ReadAllBytes($path)
    } catch {
        Log ('读取失败: ' + $_.Exception.Message)
        [void][System.Windows.Forms.MessageBox]::Show(('读取文件失败（可能被占用）: ' + $_.Exception.Message), '错误')
        return
    }
    if (-not (Test-Rom $bytes)) {
        [void][System.Windows.Forms.MessageBox]::Show(
            '锚点校验失败：这应当不是漆黑的魅影 5.0EX+BW (No-Exp) 的 ROM。' + [Environment]::NewLine +
            '为防止误改其他 ROM，已拒绝载入。', '校验失败')
        return
    }
    $script:RomPath = $path
    $script:RomBytes = $bytes
    $script:Pending.Clear()
    $lblStatus.Text = ('已载入: {0}  ({1:N0} 字节, 锚点校验通过)' -f (Split-Path $path -Leaf), $bytes.Length)
    $lblStatus.ForeColor = [System.Drawing.Color]::ForestGreen
    Log ('载入成功: ' + $path)
    Refresh-List
}
